# ============================================
# 提示词模板注册表
# 格式: {(案件类型, 人员身份): 提示词生成函数}
# ============================================
PROMPT_REGISTRY: Dict[tuple, callable] = {}


def register_prompt(case_type: str, person_type: str):
    """装饰器：注册提示词模板"""
    def decorator(func):
        PROMPT_REGISTRY[(case_type, person_type)] = func
        return func
    return decorator


def get_interrogation_prompt(
    current_status: str,
    extracted_info: dict,
    case_type: str = "盗窃案",
    person_type: str = "受害人"
) -> str:
    """
    根据案件类型和人员身份获取对应的提示词模板
    """
    # 精确匹配
    key = (case_type, person_type)
    if key in PROMPT_REGISTRY:
        return PROMPT_REGISTRY[key](current_status, extracted_info)

    # 模糊匹配：同案件类型的默认模板
    for (ct, pt), func in PROMPT_REGISTRY.items():
        if ct == case_type and pt == "默认":
            return func(current_status, extracted_info)

    # 兜底：使用盗窃案受害人模板
    return _get_default_prompt(current_status, extracted_info)


